import assert from 'node:assert/strict';
import {LapTimer} from '../game/lap-timer.js';
const lap=new LapTimer(1000,100);
let s=90;
const move=(distance,valid=true)=>{let result=null;for(let i=0;i<distance;i++){s=(s+1)%1000;result=lap.update(.01,valid?s:null)??result;}return result;};
lap.update(.01,s);move(10);assert.ok(lap.running);
assert.ok(Math.abs(move(1000)-10)<1e-8);assert.equal(lap.count,1);assert.equal(lap.best,lap.last);
move(400);move(20,false);move(580);assert.equal(lap.count,1,'Cutting invalidates lap');
move(1000);assert.equal(lap.count,2,'Next clean lap can count');
move(350);s=(s+400)%1000;lap.update(.01,s);move(250);assert.equal(lap.count,2,'Teleport cannot count');
move(200);for(let i=0;i<20;i++){s=(s+999)%1000;lap.update(.01,s);}move(820);assert.equal(lap.count,2,'Reversing invalidates lap');
const best=lap.best;lap.reset();assert.equal(lap.best,best);assert.equal(lap.running,false);
move(500);assert.equal(lap.running,false,'Recovery must wait for line');move(500);assert.equal(lap.count,0);
for(let i=0;i<5;i++){s=99;lap.update(.01,s);s=101;lap.update(.01,s);}assert.equal(lap.count,0,'Start-line oscillation cannot count');
lap.reset();lap.update(.01,99);lap.update(.01,101);
lap.update(.1,null,{safe:true});assert.equal(lap.invalid,false,'Legal pit pavement must not invalidate');
lap.update(.1,110,{safe:true,wall:true});assert.equal(lap.invalid,true,'Wall contact invalidates');
lap.reset();lap.update(.01,99);lap.update(.01,101,{wall:true});assert.equal(lap.invalid,true,'Wall touch at start line cannot be cleared by starting a lap');
console.log('Lap timing checks passed: clean laps, cuts, teleport, reverse, recovery and line oscillation.');
